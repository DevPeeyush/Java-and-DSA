package Data_type.real_number;

public class Float {
    public static void main(String[] args)
    {   float c = (float)45.22;// This method is called type casting
        float b = 45.256222528533359858525666f;// It will show only 5 to 6 significant number only
        System.out.println(b);//f suffix is used in float data type
        System.out.println(c);
    }
}
