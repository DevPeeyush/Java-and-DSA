package Data_type.real_number;

public class FloatPonitNotation {
    public static void main(String[] args)
    {
        double a = 123.5;
        double b = 1.235E2;// We can also write 1.235e2
        float c = 1.256f;
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
    }
}
