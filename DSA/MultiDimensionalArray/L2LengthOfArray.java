package MultiDimensionalArray;

public class L2LengthOfArray {
    public static void main(String[] args) {
        int[][] grid  = new int[3][4];
        int m = grid.length;
        System.out.println("Length of row : " + m);
        int n = grid[0].length;
        System.out.println("Length if column : " + n);
    }
}
